let currentLang = 'es';

function T(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key] !== undefined)
    ? TRANSLATIONS[currentLang][key]
    : (TRANSLATIONS.es[key] !== undefined ? TRANSLATIONS.es[key] : key);
}

function applyLang(lang) {
  currentLang = lang;
  const t = TRANSLATIONS[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (t[key] !== undefined) el.textContent = t[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.dataset.i18nHtml;
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.documentElement.lang = lang;
  localStorage.setItem('narbig_lang', lang);
  const btn = document.getElementById('langBtn');
  if (btn) btn.textContent = t.lang_switch;
  const wt = document.getElementById('wallText');
  if (wt && wt.style.display !== 'none') wt.innerHTML = T('wall_text');
  const mb = document.getElementById('convMoreBtn');
  if (mb) mb.innerHTML = `<div class="conv-tag">${T('conv_archive_tag')}</div><div class="conv-title">${T('conv_archive_title')}</div><div class="conv-preview">${T('conv_archive_preview')}</div>`;
  if (window.__renderEventos) window.__renderEventos();
  if (window.__renderSubstack) window.__renderSubstack();
}

(function initLang() {
  const saved = localStorage.getItem('narbig_lang');
  const nav = (navigator.language || navigator.userLanguage || 'es').toLowerCase();
  currentLang = (saved && TRANSLATIONS[saved]) ? saved : (nav.startsWith('en') ? 'en' : 'es');
  if (currentLang !== 'es') applyLang(currentLang);
  else {
    const btn = document.getElementById('langBtn');
    if (btn) btn.textContent = TRANSLATIONS.es.lang_switch;
  }
  document.documentElement.lang = currentLang;
})();

document.getElementById('langBtn').addEventListener('click', () => {
  applyLang(currentLang === 'es' ? 'en' : 'es');
});

